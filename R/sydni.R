#' SYDNI: Synthetic Data Augmentation through Noise Inference
#'
#' @description Fits a model to the observed data using either a Bayesian
#'   regression engine or a copula-based engine, then draws synthetic
#'   observations that preserve the statistical structure of the original
#'   dataset with effect size shrinkage for Type I (false positive) error
#'   correction. This allows users to generate fully synthetic “look-alike” data
#'   for model development, sensitivity analysis, and robustness checks.
#'
#' @details \code{sydni()} acts as a unified front-end for synthetic data
#'   generation, wrapping two core synthesis engines:
#'
#' \itemize{
#'   \item \code{"brm"} - fits a conditional Bayesian regression model to each
#'         target variable using the \code{brms} package and generates posterior
#'         predictive draws.
#'
#'   \item \code{"copula"} - estimates a multivariate Gaussian copula model 
#'         using the \code{copula} package,
#'         optionally stratified by covariates, and samples from the joint
#'         distribution with empirical marginal reconstruction.
#' }
#'
#'   In both cases, noise is injected into the data prior to model fitting to
#'   improve generalisation and protect individual records. The result is a
#'   synthetic dataset that mimics the joint distribution of the original data
#'   but contains no actual observations from it.
#'
#' @param data A data frame or tibble.
#' @param variables A tidyselect specification indicating which columns in
#'   \code{data} to synthesize.
#' @param covariates A tidyselect specification indicating which columns in
#'   \code{data} to use as covariates in the synthetic data generation process.
#' @param engine Character. One of \code{"brm"} or \code{"copula"}. Specifies
#'   which modeling approach to use for generating the synthetic data.
#'   \describe{
#'     \item{\code{"brm"}}{
#'       Uses \code{brms::brm()} to fit a separate Bayesian regression model
#'       for each target variable, conditioned on the covariates. Synthetic
#'       data are generated by drawing from the model’s posterior predictive distribution.
#'     }
#'     \item{\code{"copula"}}{
#'       Fits a multivariate Gaussian copula using \code{copula::normalCopula()} to
#'       capture dependencies between variables, and defines empirical marginal
#'       distributions for each column. Synthetic samples are drawn from the
#'       resulting joint distribution using \code{copula::rMvdc()}.
#'     }
#'   }
#' @param noise_method Character. One of "discrete", "truncnormal", "gaussian",
#'   or "random".
#'   \describe{
#'     \item{\code{discrete}}{
#'       For integers or ordered factors, adds noise with possible values
#'       -1, 0, or +1, where
#'       \eqn{P(\pm1) = \frac{c}{2}, \quad P(0) = 1 - c}.
#'       For continuous inputs, adds uniform noise:
#'       \eqn{\varepsilon \sim \mathrm{Uniform}(-c \cdot \mathrm{sd}(x),\; c \cdot \mathrm{sd}(x))}.
#'     }
#'     \item{\code{truncnormal}}{
#'       Adds noise from a truncated normal distribution centered at 0:
#'       \eqn{\varepsilon \sim \mathrm{TruncNormal}(0, (c \cdot \mathrm{sd}(x))^2,\;
#'       [-c \cdot \mathrm{sd}(x),\; c \cdot \mathrm{sd}(x)])}.
#'       Rounded to ±1 if input is integer-like.
#'     }
#'     \item{\code{gaussian}}{
#'       Adds noise from a normal distribution:
#'       \eqn{\varepsilon \sim \mathcal{N}(0,\; (c \cdot \mathrm{sd}(x))^2)}.
#'       Rounded if input is integer-like.
#'     }
#'     \item{\code{random}}{
#'       Adds uniform noise independent of data scale:
#'       \eqn{\varepsilon \sim \mathrm{Uniform}(-r,\; r)}.
#'     }
#'   }
#' @param c A numeric value in (0, 1). Used to scale the standard deviation of
#'   the noise. Defaults to "auto", in which case it is computed based on either
#'   \code{p} (for discrete) or \code{f} (for continuous) inputs.
#' @param round_int Logical. If TRUE (default), integer or ordered factor inputs
#'   are rounded to the nearest whole number after noise is added.
#' @param p Numeric. Probability mass to assign to jumps of ±1 in the discrete
#'   case (used only if \code{c = "auto"}).
#' @param f Numeric. Fraction of standard deviation to approximate when using
#'   continuous noise (used only if \code{c = "auto"}).
#' @param r Numeric. Maximum magnitude of noise when using \code{method =
#'   "random"}.
#' @param noise_bounds Optional numeric vector of length 2. If specified, clamps
#'   output to these lower and upper bounds. Otherwise, clamps to the range of
#'   \code{x}.
#' @param predictor_method String. Specifies the method used to determine which
#'   variables to use in the synthesis engine as predictors. Default is
#'   \code{random_information}.
#' @param predictor_k Integer. Specifies the number of variables to use in the
#'   synthesis engine as predictors. Default is \code{NULL}, which automatically
#'   determines the number.
#' @param replace Logic. Determines whether to resample with replacement.
#'   Default is \code{TRUE}.
#' @param n_aug Integer. The sample size of the synthetic data to generate.
#' @param prop_aug Numeric. Used to determine \code{n_aug} proportional to the
#'   observed data.
#' @param families A named list of families to use manually, where names
#'   correspond to column names in \code{data} and values are \code{brmsfamily}
#'   objects.
#' @param base_sd Numeric. The base standard deviation for the prior when no
#'   synthetic data is used. Default is 10.
#' @param sd_scale Numeric. Multiplier for the standard deviation of `y` to set
#'   the prior's spread. A value of 2 approximates a 95% coverage around the
#'   sample mean. Default is 2.
#' @param k Numeric. A scaling exponent controlling the rate of shrinkage.
#'   Higher values shrink the prior more aggressively as synthetic data
#'   increases. Default is 2.
#' @param chains Numeric. Number of Markov chains (Default is 2).
#' @param cores Integer. Number of CPU cores to use for parallel computation. By
#'   default, the number of available cores minus one is used:
#'   \code{parallel::detectCores() - 1}. For best performance, you may set this
#'   manually to match your system's capabilities.
#' @param iter Numeric. Number of iterations per chain, inclusive of warmup.
#'   Default is 500.
#' @param warmup Integer. Specifies the number of warmup (or burn-in)
#'   iterations. These iterations are used for step size adaptation and are not
#'   included in the posterior samples. By default, this is set to
#'   \code{floor(iter / 2)}.
#' @param thin Integer. Specifies the thinning interval for saving iterations.
#'   Every \code{thin}-th iteration is retained. Thinning helps reduce memory
#'   usage and autocorrelation in long chains. Defaults to \code{2}.
#' @param algorithm String. Specifies the estimation algorithm to use. Default
#'   is \code{"fullrank"}.
#'
#'   Available options include:
#'   \itemize{
#'     \item \code{"fullrank"}: Variational inference with a full-rank multivariate normal approximation.
#'     \item \code{"meanfield"}: Variational inference with independent normal distributions (fast but approximate).
#'     \item \code{"sampling"}: Full Bayesian inference via Markov chain Monte Carlo (MCMC).
#'     \item \code{"pathfinder"}: Quasi-variational inference using optimization-based approximations.
#'     \item \code{"laplace"}: Laplace approximation around the posterior mode.
#'     \item \code{"fixed_param"}: No inference; generates samples using fixed parameter values (e.g., for simulation).
#'   }
#'
#' @param backend Character string specifying which backend to use for fitting
#'   the Stan model. Options are \code{"rstan"} (the default) or
#'   \code{"cmdstanr"}.
#'
#'   Although \code{"rstan"} is the default, it is recommended to use
#'   \code{"cmdstanr"} for better performance and parallelization. To use
#'   \code{cmdstanr}, install the package from GitHub. For more details, see:
#'   \url{https://mc-stan.org/cmdstanr/}
#' @param seed Numeric. The seed for the random number generation for
#'   reproducibility. Default is \code{NA}.
#'
#' @return A named list with the following elements:
#' \describe{
#'   \item{\code{models}}{A list of model fit objects used to generate the synthetic data.}
#'   \item{\code{data}}{A data frame containing the synthetic data generated from the fitted models.}
#'   \item{\code{metadata}}{A list of the settings used in the function.}
#' }
#'
#' @seealso \code{\link{engine_brm}}, \code{\link{engine_copula}}
#'
#' @examples
#' \dontrun{
#'
#' sydni(
#'   data = data,
#'   variables = sprintf("a%01d", seq(5)),
#'   covariates = c("gender", "age", "income"),
#'   engine = "copula"
#' )
#'
#' }
#'
#' @export
sydni <- function(
    data,
    variables = NULL,
    covariates = NULL,
    engine = c("brm", "copula"),
    noise_method = c("truncnormal", "gaussian", "discrete", "random"),
    c = "auto",
    round_int = TRUE,
    p = 0.5,
    f = 0.5,
    r = 1,
    noise_bounds = NULL,
    predictor_method = c("random_information", "random", "information", "full"),
    predictor_k = NULL,
    replace = TRUE,
    n_aug = nrow(data),
    prop_aug = NULL,
    families = NULL,
    base_sd = 10,
    sd_scale = 2,
    k = 2,
    chains = 2,
    cores = "auto",
    iter = 500,
    warmup = floor(iter/2),
    thin = 2,
    algorithm = c("fullrank", "meanfield", "sampling", "pathfinder", "laplace", "fixed_param"),
    backend = c("rstan", "cmdstanr"),
    seed = NA
){
  

  # MATCH ARGUMENTS ---------------------------------------------------------
  
  engine <- match.arg(engine)
  noise_method <- match.arg(noise_method)
  predictor_method <- match.arg(predictor_method)
  algorithm <- match.arg(algorithm)
  backend <- match.arg(backend)
  
  # Collect all argument values
  args_used <- as.list(environment())[names(formals())]
  
  
  # WARNINGS & ERRORS -------------------------------------------------------
  
  # For backend ---
  
  if (backend == "cmdstanr") {
    if (!requireNamespace("cmdstanr", quietly = TRUE)) {
      stop(
        "The 'cmdstanr' package must be installed when using backend = 'cmdstanr'.
       Visit https://mc-stan.org/cmdstanr/ for installation instructions."
      )
    }
    if (is.null(cmdstanr::cmdstan_version(error_on_NA = FALSE))) {
      stop(
        "CmdStan must be installed and configured to use backend = 'cmdstanr'. 
      See cmdstanr::install_cmdstan()."
      )
    }
  }
  
  
  # For sampling ---
  # If both n and proportion are NULL, stop and provide error.
  if (is.null(n_aug) && is.null(prop_aug)) {
    
    stop("One of 'n_aug' or 'prop_aug' must be provided.")
    
  }
  
  # If both n and proportion are given.
  if (!is.null(n_aug) && !is.null(prop_aug)) {
    stop("Specify only one of 'n_aug' or 'prop_aug', not both.")
  }
  
  # If both n_aug and prop_aug are specified, default to n_aug
  if (!is.null(n_aug) && !is.null(prop_aug)) {
    
    warning("Both 'n_aug' and 'prop_aug' specified. Defaulting to 'n_aug'.")
    prop_aug <- NULL
    
  }
  # If n_aug is greater than the length of the observed data, force replace to be TRUE.
  if (!is.null(n_aug)) {
    if (n_aug > nrow(data) && isFALSE(replace)) {
      
      warning("'replace' cannot be FALSE when 'n_aug' > n of the observed data. Setting 'replace = TRUE'.")
      replace <- TRUE
      
    }
  }
  
  # If prop_aug is greater than 1, force replace to be TRUE.
  if (!is.null(prop_aug)){
    if (prop_aug > 1 && isFALSE(replace)) {
      
      warning("'replace' cannot be FALSE when 'prop_aug' > 1. Setting 'replace = TRUE'.")
      replace <- TRUE
      
    }
  }
  
  
  
  # For n ---
  if (!is.null(n_aug)) {
    
    # If n is not a numeric value, stop and provide error.
    if (!is.numeric(n_aug)) {
      stop("'n_aug' must be numeric.")
    }
    
    # If n is <1, stop and provide error.
    if (n_aug < 1) {
      stop("'n_aug' must have a value greater than or equal to 1.")
    }
    
    # If n is a float, round to nearest whole number and provide warning.
    if (n_aug %% 1 != 0) {
      warning(paste0("'n_aug' is not an integer; rounding to the nearest whole number, n = ", round(n_aug)))
      n_aug <- round(n_aug)
    }
    
  }
  
  
  # For proportion ---
  if (!is.null(prop_aug)) {
    
    # If proportion is not a numeric value, stop and provide error.
    if (!is.numeric(prop_aug)) {
      stop("'prop_aug' must be numeric.")
    }
    
    # If proportion is <0, stop and provide error.
    if (prop_aug <= 0) {
      stop("'prop_aug' must have a value greater than 0.")
    }
    
  }
  
  
  # For predictor k ---
  if (!is.null(predictor_k) && predictor_k > length(variables)-1) {
    
    predictor_k <- length(variables)-1
    warning(
      paste0("Predictor k > variables - 1. Reducing k to ", predictor_k, ".")
    )
    
  }
  
  if (is.null(predictor_k)) {
    
    predictor_k <- round((length(variables)-1) / 3)
    message(
      paste0("Predictor k not specified. Defaulting to ", predictor_k, ".")
    )
    
  }
  
  
  # ENGINE ------------------------------------------------------------------
  
  # If variables is NULL, then get all variables
  if(is.null(variables)) {
    
    variables <- setdiff(colnames(data), covariates)
    
  }
  
  # Select only relevant variables within data
  data <- data |> 
    dplyr::select(
      dplyr::all_of(variables), # Relevant variables
      dplyr::all_of(covariates) # Relevant covariates
    )
  
  # If n_aug is missing but prop_aug is given
  if (is.null(n_aug) && !is.null(prop_aug)) {
    
    n_aug <- round(nrow(data) * prop_aug)
    
  }
  
  
  # BRM Engine ---
  
  if (engine == "brm") {
    
    synth <- engine_brm(
      data = data,
      variables = variables,
      covariates = covariates,
      noise_method = noise_method,
      noise_bounds = noise_bounds,
      c = c,
      p = p,
      r = r,
      f = f,
      round_int = round_int,
      predictor_method = predictor_method,
      predictor_k = predictor_k,
      replace = replace,
      n_aug = n_aug,
      families = families,
      base_sd = base_sd,
      sd_scale = sd_scale,
      k = k,
      chains = chains,
      cores = cores,
      iter = iter,
      warmup = warmup,
      thin = thin,
      algorithm = algorithm,
      seed = seed,
      backend = backend
    )
    
  }
  
  
  
  # COPULA Engine ---
  
  if (engine == "copula") {
    
    synth <- engine_copula(
      data = data,
      variables = variables,
      covariates = covariates,
      noise_method = noise_method,
      noise_bounds = noise_bounds,
      c = c,
      p = p,
      r = r,
      round_int = round_int,
      n_aug = n_aug
    )
    
  }
  
  
  
  # COMPILE RETURN OBJECTS --------------------------------------------------
  
  return_list <- list(
    models = synth$models,
    data = synth$data,
    meta = args_used
  )
  
  return(return_list)
  
}

